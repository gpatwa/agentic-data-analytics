"""S6 evaluation of `docs/design/SEMANTIC_SYNONYMS_DESIGN.md`: what confirming instead of refusing does, with a scripted "user", offline and with fakes.

Every case is a question and the intent a model is assumed to have returned. A question the echo or coverage check refuses is the one the person
would be ASKED about. Two scripted users answer: a CAREFUL one who confirms a reading only when it is right, and a HABITUAL one who always says yes.
The figure the owner needs is the second: how many WRONG readings a habitually confirming user lets through. Author-written corpus plus the owner's
hold-out (written by a fresh agent, adopted 2026-11-20). Thresholds are not proposed here: this is a policy decision for the owner.
"""

from __future__ import annotations

import json
import sys
from typing import Any

from reference_stack import coverage_eval as ev

RIGHT = {"valid", "faithful"}  # the reading is what the question asks
WRONG = {"dropped", "omitted", "near_miss"}  # the reading is not what the question asks


def _asked(rows: list[tuple]) -> list[tuple]:
    return [r for r in rows if r[5] != "answered"]  # refused by the echo or the coverage check, so the person would be asked


def run() -> dict[str, Any]:
    rows = [(cid, group, q, metric, *ev.verdicts(q, metric, extra)) for cid, group, q, metric, extra in ev.CASES]
    # row layout: (id, group, question, metric, echo_alone, echo_plus_coverage)
    right, wrong = [r for r in rows if r[1] in RIGHT], [r for r in rows if r[1] in WRONG]
    asked_right, asked_wrong = _asked(right), _asked(wrong)
    cases = json.loads(ev.HOLDOUT.read_text()).get("cases", []) if ev.HOLDOUT.exists() else []
    h = [(c["expect"], *ev.verdicts(c["question"], c["metric"], {})) for c in cases]
    h_right = [x for x in h if x[0] == "answer"]
    h_wrong = [x for x in h if x[0] == "refuse"]
    return {
        "corpus_right": len(right), "corpus_right_asked": len(asked_right),  # careful user: all become answers
        "corpus_wrong": len(wrong), "corpus_wrong_asked": len(asked_wrong),  # careful user rejects all; habitual lets all through
        "corpus_wrong_already_answered": len(wrong) - len(asked_wrong),
        "holdout_right": len(h_right), "holdout_right_asked": sum(1 for x in h_right if x[2] != "answered"),
        "holdout_wrong": len(h_wrong), "holdout_wrong_asked": sum(1 for x in h_wrong if x[2] != "answered"),
    }


def render_markdown() -> str:
    r = run()
    return "\n".join([
        "# S6: confirm instead of refuse, scripted-user evaluation (generated)", "",
        "Generated by `services/analytics-api/reference_stack/interpretation_eval.py`; a test keeps this file equal to the generator. Fakes only: no model, no warehouse. "
        "Each question is paired with the reading a model is assumed to have returned; a question the echo or coverage check refuses is the one the person is **asked** about. "
        "A **careful** user confirms only a right reading. A **habitual** user always says yes. Author-written corpus and the owner's hold-out; thresholds are not proposed here.", "",
        "| Group | Count | Asked (refused with the coverage check on) | Careful user | Habitual user |", "|---|---|---|---|---|",
        f"| Right readings, corpus | {r['corpus_right']} | {r['corpus_right_asked']} | {r['corpus_right_asked']} refusals become answers | same |",
        f"| Wrong readings, corpus | {r['corpus_wrong']} | {r['corpus_wrong_asked']} | all {r['corpus_wrong_asked']} rejected | **{r['corpus_wrong_asked']} wrong answers** |",
        f"| Right readings, hold-out | {r['holdout_right']} | {r['holdout_right_asked']} | {r['holdout_right_asked']} refusals become answers | same |",
        f"| Wrong readings, hold-out | {r['holdout_wrong']} | {r['holdout_wrong_asked']} | all {r['holdout_wrong_asked']} rejected | **{r['holdout_wrong_asked']} wrong answers** |", "",
        f"{r['corpus_wrong_already_answered']} wrong corpus readings are answered without being asked even with the coverage check on; S6 changes nothing for those. (With the coverage check off, many dropped constraints are answered silently: see the K2 report.)", "",
        "## What this says", "",
        "- With a careful user every refusal of a right reading becomes an answer and every wrong reading is still rejected: S6 is strictly better than refusing.",
        "- With a habitual user a wrong reading is **answered** every time it is asked about. S6 turns \"no wrong answer\" into \"no wrong answer unless the person confirms the wrong reading\". "
        "The prompt states the reading in plain words (\"with no other filter, no time period and no sort\", and any filter the metric always applies), which is what makes a dropped condition visible; a person who does not read it is not protected.",
        "- A confirm rate near 100% in use is a sign the wording rules are too tight or the person is not reading, not proof of correctness.",
        "- The coverage check (K3) is still worth enabling: it is what *finds* the dropped constraint and turns it into a question instead of a silent wrong answer.", "",
        "This does not measure real people, a real model, or other contracts. Whether to accept the habitual-user risk is the owner's policy decision.",
    ]) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render_markdown())
